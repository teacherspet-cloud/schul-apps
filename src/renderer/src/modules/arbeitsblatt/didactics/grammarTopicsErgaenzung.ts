import type { GrammarScale, GrammarTopic } from './grammarTopics'

type Eingabe = Omit<GrammarTopic, 'subject' | 'scale' | 'stage' | 'formatsText'> & {
  scale?: GrammarScale
  stage?: string
  formatsText?: string
}

/** Stufenangabe wie in der erzeugten Tabelle: „3" oder „3–5" */
const stufe = (from: number, to: number): string => (from === to ? `${from}` : `${from}–${to}`)

function fach(subject: string, liste: Eingabe[]): GrammarTopic[] {
  return liste.map((e) => ({
    ...e,
    subject,
    scale: e.scale ?? 'lernjahr',
    stage: e.stage ?? stufe(e.from, e.to),
    formatsText: e.formatsText ?? e.description ?? ''
  }))
}

