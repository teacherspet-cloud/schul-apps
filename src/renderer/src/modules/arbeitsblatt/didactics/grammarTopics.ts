import { ERGAENZTE_GRAMMATIKTHEMEN } from './grammarTopicsErgaenzung'

export type GrammarScale = 'lernjahr' | 'jahrgang' | 'erwerbsstufe'

export interface GrammarTopic {
  id: string
  subject: string
  /** Lernjahr (Fremdsprachen), Jahrgang (Deutsch) oder Erwerbsstufe (DaZ) */
  scale: GrammarScale
  /** Bezeichnung auf Deutsch – so steht sie auf dem Arbeitsblatt */
  label: string
  /** Fachbezeichnung bzw. fremdsprachlicher Terminus */
  term: string
  /** Bereich für die Gliederung der Auswahl */
  area: string
  from: number
  to: number
  /** Spanisch als spät beginnende Fremdsprache: dort früher */
  lateStart?: number
  /** Rohangabe der Stufe, wo sie feiner ist als eine Zahl (DaZ 1a/1b, Latein „Lektürephase") */
  stage: string
  /** GER-Niveau der Ersteinführung; bei Latein die Phase, bei Deutsch die Stufe */
  level: string
  /** Quellen widersprechen sich – in der Auswahl wird darauf hingewiesen */
  contested?: boolean
  /** Zunächst nur zum Erkennen, nicht zum Bilden */
  receptive?: boolean
  /** Typische Fehlerquellen, überwiegend Interferenzen mit dem Deutschen */
  errors: string
  /** Übungsformate als Kennung (siehe GRAMMAR_FORMATS in grammar.ts) */
  formats: string[]
  /** Formatempfehlung im Wortlaut der Recherche */
  formatsText: string
  /** Kurzbeschreibung der Form (ergänzte Themen, siehe grammarTopicsErgaenzung.ts) */
  description?: string
  /** Beispiele in der Zielsprache */
  examples?: string[]
  /** Beleg der Einordnung, knapp (Lehrplan, Lehrwerk oder „Faustregel") */
  source?: string
}

